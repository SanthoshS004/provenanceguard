import React, { useEffect, useState } from 'react';
import { useAuth } from '../context/AuthContext';
import { useTenant } from '../context/TenantContext';
import { getAuditLogs } from '../services/api';
import { AuditLogEntry } from '../types';
import { PageHeader } from './ui/PageHeader';
import { Button } from './ui/Button';
import { Badge } from './ui/Badge';
import { TechnicalValue } from './ui/TechnicalValue';
import { EmptyState } from './ui/EmptyState';
import { FileLock2, ChevronLeft, ChevronRight, Search } from 'lucide-react';

export const AuditLogViewer: React.FC = () => {
  const { session } = useAuth();
  const { selectedOrgId } = useTenant();

  const [logs, setLogs] = useState<AuditLogEntry[]>([]);
  const [total, setTotal] = useState<number>(0);
  const [offset, setOffset] = useState<number>(0);
  const limit = 15;
  const [actionFilter, setActionFilter] = useState<string>('');

  const fetchAuditStream = async () => {
    if (!session?.token) return;
    try {
      const res = await getAuditLogs(session.token, limit, offset, actionFilter || undefined, selectedOrgId);
      setLogs(res.items);
      setTotal(res.total);
    } catch {
      setLogs([]);
      setTotal(0);
    }
  };

  useEffect(() => {
    fetchAuditStream();
  }, [session, selectedOrgId, offset, actionFilter]);

  const handleNextPage = () => {
    if (offset + limit < total) {
      setOffset(offset + limit);
    }
  };

  const handlePrevPage = () => {
    if (offset >= limit) {
      setOffset(offset - limit);
    }
  };

  return (
    <div className="space-y-6">
      <PageHeader
        category="ADMINISTRATION"
        title="Audit Log Stream"
        description="Immutable database SIEM audit stream protected by Organization-scoped advisory locks & hash-chain integrity"
        actions={
          <div className="relative">
            <Search className="absolute left-3 top-2.5 h-4 w-4 text-[#667B94]" />
            <input
              type="text"
              placeholder="Filter by action (e.g. VERIFICATION_RUN)..."
              value={actionFilter}
              onChange={(e) => {
                setActionFilter(e.target.value);
                setOffset(0);
              }}
              className="rounded-lg border border-[#1C2B40] bg-[#0A1424] pl-9 pr-3.5 py-1.5 text-xs text-[#F4F8FC] placeholder-[#667B94] focus:border-[#168DCC] focus:outline-none w-64 md:w-80"
            />
          </div>
        }
      />

      {/* Main Audit Log Table Card */}
      <div className="rounded-xl border border-[#1C2B40] bg-[#0D1728] p-5 md:p-6 space-y-5">
        <div className="flex items-center justify-between border-b border-[#1C2B40] pb-4">
          <span className="text-sm font-bold text-[#F4F8FC] flex items-center gap-2.5">
            <FileLock2 className="h-5 w-5 text-[#00B8FF]" />
            <span>SIEM Security Event Stream ({total} Total Records)</span>
          </span>

          <div className="flex items-center gap-4 text-xs text-[#91A5BD]">
            <span>
              Showing {total === 0 ? 0 : offset + 1} - {Math.min(offset + limit, total)} of {total}
            </span>
            <div className="flex items-center gap-1.5">
              <Button
                variant="secondary"
                disabled={offset === 0}
                onClick={handlePrevPage}
                icon={<ChevronLeft className="h-4 w-4" />}
                className="px-2 py-1"
              />
              <Button
                variant="secondary"
                disabled={offset + limit >= total}
                onClick={handleNextPage}
                icon={<ChevronRight className="h-4 w-4" />}
                className="px-2 py-1"
              />
            </div>
          </div>
        </div>

        {logs.length === 0 ? (
          <EmptyState
            icon={FileLock2}
            title="No audit events yet"
            description="Security events generated by verification, policy, and administrative actions will appear here."
          />
        ) : (
          <div className="overflow-x-auto">
            <table className="w-full text-left text-xs text-[#91A5BD] min-w-[850px]">
              <thead className="border-b border-[#1C2B40] bg-[#0A1424] font-semibold text-[#91A5BD]">
                <tr>
                  <th className="py-3 px-4">Event ID</th>
                  <th className="py-3 px-4">Actor ID</th>
                  <th className="py-3 px-4">Action</th>
                  <th className="py-3 px-4">Resource Target</th>
                  <th className="py-3 px-4">Result</th>
                  <th className="py-3 px-4">Timestamp</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-[#1C2B40]/60">
                {logs.map((log) => (
                  <tr key={log.id} className="hover:bg-[#111F32] transition h-12">
                    <td className="py-3 px-4">
                      <TechnicalValue value={log.id} truncateLength={8} />
                    </td>
                    <td className="py-3 px-4">
                      <TechnicalValue value={log.actor_id} truncateLength={12} />
                    </td>
                    <td className="py-3 px-4 font-semibold text-[#F4F8FC]">{log.action}</td>
                    <td className="py-3 px-4 font-mono text-[#91A5BD]">{log.resource}</td>
                    <td className="py-3 px-4">
                      {log.result === 'PASS' || log.result === 'SUCCESS' ? (
                        <Badge variant="pass">{log.result}</Badge>
                      ) : (
                        <Badge variant="block">{log.result}</Badge>
                      )}
                    </td>
                    <td className="py-3 px-4 text-[#91A5BD]">{new Date(log.created_at).toLocaleString()}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </div>
    </div>
  );
};

